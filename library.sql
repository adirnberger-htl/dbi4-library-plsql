DROP TABLE Library_Book_Rental;
DROP TABLE Library_Book;
DROP TABLE Library_ClientLanguage;
DROP TABLE Library_Favorite_genre;
DROP TABLE Library_Genre;
DROP TABLE Library_Client;
DROP TABLE Library_Language;
DROP TABLE Library_media_type;
DROP TABLE Library_Author;
DROP SEQUENCE Library_Book_Serial;

CREATE SEQUENCE Library_Book_Serial
    START WITH 10000
    INCREMENT BY 1
    NOCACHE;

CREATE TABLE Library_Author
(
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name    VARCHAR2(30) NOT NULL,
    last_name     VARCHAR2(30) NOT NULL,
    date_of_birth DATE         NOT NULL,
    date_of_death DATE         NULL,
    CONSTRAINT Author_PK PRIMARY KEY (id)
);

CREATE TABLE Library_media_type
( -- hardcover, paperback, newspaper, audiobook, ...
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    media_type VARCHAR2(20),
    base_fee   NUMBER(3, 2),
    CONSTRAINT Media_Type_PK PRIMARY KEY (id)
);

CREATE TABLE Library_Genre
( -- fiction, crime, thriller, romance, children, young adult, science, politics, ...
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    genre VARCHAR2(20),
    CONSTRAINT Genre_PK PRIMARY KEY (id)
);

CREATE TABLE Library_Client
(
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(30) NOT NULL,
    last_name  VARCHAR2(30) NOT NULL,
    email      VARCHAR2(50),
    CONSTRAINT Client_PK PRIMARY KEY (id)
);

CREATE TABLE Library_Language
(
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    language_short VARCHAR2(3)  NOT NULL,
    language       VARCHAR2(30) NOT NULL,
    CONSTRAINT Language_PK PRIMARY KEY (id)
);

CREATE TABLE Library_Book
(
    id number(10) GENERATED BY DEFAULT AS IDENTITY,
    author        NUMBER(8)    NULL,
    title         VARCHAR2(50) NOT NULL,
    ISBN          VARCHAR2(13) NOT NULL,
    serial_number NUMBER(10) DEFAULT Library_Book_Serial.nextval NOT NULL,
    book_language number(4) NOT NULL,
    book_genre    NUMBER(4)    NOT NULL,
    media_type    NUMBER(4)    NOT NULL,
    shelf         VARCHAR2(15),

    CONSTRAINT Book_PK PRIMARY KEY (id),
    CONSTRAINT Book_Author FOREIGN KEY (author) REFERENCES Library_Author (id) ON DELETE SET NULL,
    CONSTRAINT Book_media_type FOREIGN KEY (media_type) REFERENCES Library_media_type(id),
    CONSTRAINT Book_BGenre FOREIGN KEY (book_genre) REFERENCES Library_Genre(id),
    CONSTRAINT Book_BLanguage FOREIGN KEY (book_language) REFERENCES Library_Language
);


CREATE TABLE Library_ClientLanguage
(
    client_id   NUMBER(8) NOT NULL,
    language_id NUMBER(3) NOT NULL,
    CONSTRAINT ClientLanguage_PK PRIMARY KEY (client_id, language_id),
    CONSTRAINT ClientLanguage_Client FOREIGN KEY (client_id) REFERENCES Library_Client (id) ON DELETE CASCADE,
    CONSTRAINT ClientLanguage_Language FOREIGN KEY (language_id) REFERENCES Library_Language(id) ON DELETE CASCADE
);

CREATE TABLE Library_Favorite_genre
(
    client_id NUMBER(8) NOT NULL,
    genre_id  NUMBER(4) NOT NULL,
    CONSTRAINT ClientGenre_PK PRIMARY KEY (client_id, genre_id),
    CONSTRAINT ClientGenre_Client FOREIGN KEY (client_id) REFERENCES Library_Client (id) ON DELETE CASCADE,
    CONSTRAINT BookFavorite_Genre FOREIGN KEY (genre_id) REFERENCES Library_Genre(id) ON DELETE CASCADE
);

CREATE TABLE Library_Book_Rental
(
    id           NUMBER                 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    client_id    NUMBER(8)              NOT NULL,
    book_id      NUMBER(8)              NOT NULL,
    booking_time TIMESTAMP              NOT NULL,
    return_date  DATE                   NULL,
    fee          NUMBER(6, 2)           NOT NULL,
    late_fee     NUMBER(6, 2),
    amount_paid  number(6, 2) DEFAULT 0 NOT NULL,
    all_paid     NUMBER(1)    DEFAULT 0 NOT NULL,
    CONSTRAINT Book_Rental_PK PRIMARY KEY (id),
    CONSTRAINT Book_Rental_Client FOREIGN KEY (client_id) REFERENCES Library_Client (id) ON DELETE CASCADE ,
    CONSTRAINT Lease_Book FOREIGN KEY (book_id) REFERENCES Library_Book(id) ON DELETE CASCADE
);

