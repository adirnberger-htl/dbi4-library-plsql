CREATE TABLE Customer (
    CustomerId NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FirstName VARCHAR2(100) NOT NULL,
    LastName VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_customer PRIMARY KEY (CustomerId)
);

CREATE TABLE Orders (
    OrderId NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CustomerId NUMBER,
    OderDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    Total NUMBER NOT NULL,
    CONSTRAINT pk_order PRIMARY KEY (OrderId),
    CONSTRAINT fk_orders_customer FOREIGN KEY (CustomerId)
                    REFERENCES Customer (CustomerId)
);

--------------------------------------------------------------

CREATE TABLE Students (
    StudentId NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FirstName VARCHAR2(100) NOT NULL,
    LastName VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (StudentId)
);

CREATE TABLE Classes (
    ClassId NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR2(100) NOT NULL,
    StartTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_class PRIMARY KEY (ClassId)
);

CREATE TABLE Timetable (
    Name VARCHAR2(100),
    ClassId NUMBER,
    StudentId NUMBER,
    CONSTRAINT pk_timetable PRIMARY KEY (ClassId, StudentId),
    CONSTRAINT fk_timetable_class FOREIGN KEY (ClassId)
                       REFERENCES Classes (ClassId) ON DELETE CASCADE,  -- DELETE ON CASCADE -> Delete Reference with Student
    CONSTRAINT fk_timetable_student FOREIGN KEY (StudentId)
                       REFERENCES Students (StudentId) ON DELETE CASCADE
);

